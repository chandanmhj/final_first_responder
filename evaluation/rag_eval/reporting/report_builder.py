"""Write docs/evaluation/REPORT.md from saved results."""
import os
from collections import defaultdict

from ..config import OUT_FIGURES, ROOT
from ..metrics.statistics import bootstrap_ci


def build(rows, figure_names):
    by = defaultdict(lambda: defaultdict(list))
    for r in rows:
        for k, v in r.items():
            if isinstance(v, float):
                by[r["variant"]][k].append(v)
    lines = ["# Evaluation report", "", "Generated by `python -m rag_eval.cli run`. Seed questions are a smoke test, not paper results.", "",
             "| Variant | MRR (95% CI) | Mean latency ms |", "|---|---|---|"]
    for v, m in by.items():
        mean, lo, hi = bootstrap_ci(m["mrr"])
        lines.append(f"| {v} | {mean:.3f} ({lo:.3f} to {hi:.3f}) | {sum(m['latency_ms']) / len(m['latency_ms']):.1f} |")
    lines += [""] + [f"![{n}](figures/{n})" for n in figure_names if os.path.exists(os.path.join(OUT_FIGURES, n))]
    path = os.path.join(ROOT, "docs", "evaluation", "REPORT.md")
    open(path, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    return path
